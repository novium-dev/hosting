-- API keys, replacing the unused placeholder table from the initial migration.
--
-- A key always belongs to the user who created it: its effective permissions are
-- re-derived from that user on every request and intersected with the bits
-- stored here, so revoking a user's access revokes their keys' access too and a
-- key can never outgrow its owner.
--
-- `project` NULL means an instance-wide ("admin") key, which carries management
-- permissions; a non-NULL project scopes the key to that project's servers.
--
-- Only the SHA-256 of the token is stored — the token itself is shown once, at
-- creation. `token_prefix` is the (non-secret) leading segment so a key can
-- still be recognised in the UI.
DROP TABLE api_keys;

CREATE TABLE api_keys (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(64) NOT NULL,
    token_hash char(64) NOT NULL UNIQUE,
    token_prefix varchar(16) NOT NULL,
    "user" integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    project char(6) REFERENCES projects (id) ON DELETE CASCADE,
    permissions bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    last_used timestamptz
);

CREATE INDEX api_keys_user_idx ON api_keys ("user");

CREATE INDEX api_keys_project_idx ON api_keys (project);

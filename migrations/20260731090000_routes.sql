CREATE TYPE route_status AS ENUM ('pending', 'active', 'failed');

CREATE TABLE route_domains (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain varchar(253) NOT NULL UNIQUE,
    provider varchar(64) NOT NULL,
    provider_domain_id varchar(64),
    srv_service varchar(32),
    https boolean NOT NULL DEFAULT true,
    private boolean NOT NULL DEFAULT false
);

CREATE TABLE route_domain_projects (
    domain integer NOT NULL REFERENCES route_domains (id) ON DELETE CASCADE,
    project char(6) NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    PRIMARY KEY (domain, project)
);

CREATE INDEX route_domain_projects_project_idx ON route_domain_projects (project);

CREATE TABLE routes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server char(6) NOT NULL REFERENCES servers (id) ON DELETE CASCADE,
    domain integer NOT NULL REFERENCES route_domains (id) ON DELETE RESTRICT,
    subdomain varchar(63) NOT NULL,
    port integer NOT NULL REFERENCES server_ports (id) ON DELETE CASCADE,
    https boolean NOT NULL DEFAULT true,
    status route_status NOT NULL DEFAULT 'pending',
    external_ids text[] NOT NULL DEFAULT '{}',
    records jsonb NOT NULL DEFAULT '[]'::jsonb,
    UNIQUE (domain, subdomain)
);

CREATE INDEX routes_server_idx ON routes (server);

CREATE INDEX routes_port_idx ON routes (port);

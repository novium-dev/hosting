CREATE TYPE network_protocol AS ENUM ('tcp', 'udp');

CREATE TYPE route_status AS ENUM ('pending', 'active', 'failed');

CREATE TYPE route_kind AS ENUM ('http', 'tcp', 'udp');

CREATE TABLE users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(32) NOT NULL,
    auth_id varchar(255) NOT NULL UNIQUE,
    role integer NOT NULL DEFAULT 0,
    email varchar(255) NOT NULL,
    language varchar(255) NOT NULL DEFAULT 'en',
    first_name varchar(255),
    last_name varchar(255),
    daemon_password char(32)
);

CREATE TABLE user_ssh_keys (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "user" integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name varchar(64) NOT NULL,
    public_key varchar(4096) NOT NULL,
    fingerprint_sha512 char(128) NOT NULL,
    UNIQUE ("user", fingerprint_sha512)
);

CREATE TABLE regions (
    id char(6) PRIMARY KEY,
    display varchar(64) NOT NULL,
    slug varchar(64) NOT NULL UNIQUE
);

CREATE TABLE nodes (
    id uuid PRIMARY KEY,
    display varchar(64) NOT NULL,
    url varchar(255) NOT NULL,
    default_host varchar(255) NOT NULL,
    default_bind varchar(64) NOT NULL,
    maintenance boolean NOT NULL DEFAULT false,
    ssh_port integer,
    ssh_host varchar(255),
    region char(6) NOT NULL REFERENCES regions (id)
);

CREATE INDEX nodes_region_idx ON nodes (region);

CREATE TABLE node_server_storage (
    node uuid NOT NULL REFERENCES nodes (id) ON DELETE CASCADE,
    storage varchar(64) NOT NULL,
    PRIMARY KEY (node, storage)
);

CREATE TABLE node_backup_storage (
    node uuid NOT NULL REFERENCES nodes (id) ON DELETE CASCADE,
    storage varchar(64) NOT NULL,
    PRIMARY KEY (node, storage)
);

CREATE TABLE node_ports (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node uuid NOT NULL REFERENCES nodes (id) ON DELETE CASCADE,
    protocol network_protocol NOT NULL,
    start integer NOT NULL CHECK (start BETWEEN 0 AND 65535),
    "end" integer NOT NULL CHECK ("end" BETWEEN 0 AND 65535 AND "end" >= start)
);

CREATE TABLE projects (
    id char(6) PRIMARY KEY,
    slug varchar(64) NOT NULL UNIQUE,
    name varchar(64) NOT NULL,
    owner integer NOT NULL REFERENCES users (id)
);

CREATE INDEX projects_owner_idx ON projects (owner);

CREATE TABLE project_users (
    "user" integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    project char(6) NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    permissions bigint NOT NULL,
    PRIMARY KEY ("user", project)
);

CREATE INDEX project_users_project_user_idx ON project_users (project, "user");

CREATE TABLE project_features (
    project char(6) NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    feature varchar(64) NOT NULL,
    PRIMARY KEY (project, feature)
);

CREATE TABLE servers (
    id char(6) PRIMARY KEY,
    name varchar(64) NOT NULL,
    node uuid NOT NULL REFERENCES nodes (id),
    node_server_id integer NOT NULL CHECK (node_server_id >= 0),
    project char(6) NOT NULL REFERENCES projects (id),
    cpu real,
    ram integer CHECK (ram IS NULL OR ram >= 0),
    swap integer CHECK (swap IS NULL OR swap >= 0),
    disk bigint CHECK (disk IS NULL OR disk >= 0),
    storage varchar(64) NOT NULL,
    template varchar(64) NOT NULL,
    template_extra jsonb NOT NULL,
    custom_dockerfile varchar(10000),
    suspended boolean NOT NULL DEFAULT false,
    suspension_reason varchar(512),
    internet_access boolean NOT NULL DEFAULT true,
    backup_limit integer CHECK (backup_limit IS NULL OR backup_limit >= 0),
    UNIQUE (node, node_server_id),
    CONSTRAINT servers_suspension_reason_check CHECK (
        (suspended AND suspension_reason IS NOT NULL)
        OR (NOT suspended AND suspension_reason IS NULL)
    )
);

CREATE INDEX servers_project_idx ON servers (project);

CREATE TABLE server_ports (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server char(6) NOT NULL REFERENCES servers (id) ON DELETE CASCADE,
    name varchar(255) NOT NULL DEFAULT 'Unknown',
    host varchar(255) NOT NULL,
    internal_port integer NOT NULL CHECK (internal_port BETWEEN 0 AND 65535),
    external_ip varchar(255) NOT NULL,
    external_port int4range NOT NULL CHECK (
        NOT isempty(external_port)
        AND external_port <@ int4range(0, 65535, '[]')
    ),
    protocol network_protocol NOT NULL,
    http boolean NOT NULL DEFAULT false
);

CREATE INDEX server_ports_server_idx ON server_ports (server);

CREATE TABLE server_resources (
    server char(6) NOT NULL REFERENCES servers (id) ON DELETE CASCADE,
    provider varchar(32) NOT NULL,
    project varchar(128) NOT NULL,
    version varchar(128) NOT NULL,
    resource_type varchar(32) NOT NULL,
    file_name varchar(255) NOT NULL,
    title varchar(255) NOT NULL,
    installed_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (server, provider, project)
);

CREATE INDEX server_resources_server_idx ON server_resources (server);

CREATE TABLE server_modpacks (
    server char(6) PRIMARY KEY REFERENCES servers (id) ON DELETE CASCADE,
    provider varchar(32) NOT NULL,
    project varchar(128) NOT NULL,
    version varchar(128) NOT NULL,
    title varchar(255) NOT NULL,
    files text[] NOT NULL DEFAULT '{}',
    installed_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE server_licenses (
    server char(6) NOT NULL REFERENCES servers (id) ON DELETE CASCADE,
    license varchar(64) NOT NULL,
    accepted_by integer REFERENCES users (id) ON DELETE SET NULL,
    accepted_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (server, license)
);

CREATE TABLE api_keys (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(64) NOT NULL,
    token_hash char(64) NOT NULL UNIQUE,
    token_prefix varchar(16) NOT NULL,
    "user" integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    project char(6) REFERENCES projects (id) ON DELETE CASCADE,
    permissions bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    last_used timestamptz
);

CREATE INDEX api_keys_user_idx ON api_keys ("user");

CREATE INDEX api_keys_project_idx ON api_keys (project);

CREATE TABLE route_domains (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain varchar(253) NOT NULL UNIQUE,
    pangolin_domain_id varchar(64),
    cloudflare_zone_id varchar(64),
    https boolean NOT NULL DEFAULT true,
    private boolean NOT NULL DEFAULT false
);

CREATE TABLE route_domain_projects (
    domain integer NOT NULL REFERENCES route_domains (id) ON DELETE CASCADE,
    project char(6) NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    PRIMARY KEY (domain, project)
);

CREATE INDEX route_domain_projects_project_idx ON route_domain_projects (project);

CREATE TABLE routes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server char(6) NOT NULL REFERENCES servers (id) ON DELETE CASCADE,
    domain integer NOT NULL REFERENCES route_domains (id) ON DELETE RESTRICT,
    subdomain varchar(63) NOT NULL,
    port integer NOT NULL REFERENCES server_ports (id) ON DELETE CASCADE,
    kind route_kind NOT NULL,
    service varchar(32),
    https boolean NOT NULL DEFAULT true,
    status route_status NOT NULL DEFAULT 'pending',
    external_ids text[] NOT NULL DEFAULT '{}',
    records jsonb NOT NULL DEFAULT '[]'::jsonb,
    UNIQUE (domain, subdomain)
);

CREATE INDEX routes_server_idx ON routes (server);

CREATE INDEX routes_port_idx ON routes (port);

CREATE TABLE database_hosts (
    id uuid PRIMARY KEY,
    display varchar(64) NOT NULL,
    region char(6) NOT NULL REFERENCES regions (id),
    url text NOT NULL,
    token text NOT NULL,
    public_host varchar(255) NOT NULL,
    maintenance boolean NOT NULL DEFAULT false
);

CREATE INDEX database_hosts_region_idx ON database_hosts (region);

CREATE TABLE database_host_ports (
    host uuid NOT NULL REFERENCES database_hosts (id) ON DELETE CASCADE,
    type varchar(16) NOT NULL,
    port integer NOT NULL,
    PRIMARY KEY (host, type)
);

CREATE TABLE database_instances (
    id uuid PRIMARY KEY,
    host uuid NOT NULL REFERENCES database_hosts (id),
    project char(6) NOT NULL REFERENCES projects (id),
    type varchar(16) NOT NULL,
    display varchar(64) NOT NULL,
    created timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX database_instances_host_idx ON database_instances (host);

CREATE INDEX database_instances_project_idx ON database_instances (project);

CREATE INDEX database_instances_type_idx ON database_instances (type);

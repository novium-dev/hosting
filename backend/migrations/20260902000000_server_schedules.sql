CREATE TYPE schedule_policy AS ENUM ('always', 'running', 'stopped');

CREATE TABLE server_schedules (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server char(6) NOT NULL REFERENCES servers (id) ON DELETE CASCADE,
    node_schedule_id integer CHECK (node_schedule_id IS NULL OR node_schedule_id >= 0),
    name varchar(64) NOT NULL,
    enabled boolean NOT NULL DEFAULT true,
    policy schedule_policy NOT NULL DEFAULT 'always',
    cron varchar(256) NOT NULL,
    timezone varchar(64) NOT NULL,
    tasks jsonb NOT NULL,
    created timestamptz NOT NULL DEFAULT now(),
    UNIQUE (server, node_schedule_id)
);

CREATE INDEX server_schedules_server_idx ON server_schedules (server);

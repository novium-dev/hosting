CREATE TYPE network_protocol AS ENUM ('tcp', 'udp');

CREATE TABLE nodes (
    id uuid PRIMARY KEY,
    display varchar(64) NOT NULL,
    url varchar(255) NOT NULL,
    default_host varchar(255) NOT NULL,
    default_bind varchar(64) NOT NULL,
    maintenance boolean NOT NULL DEFAULT false
);

CREATE TABLE node_server_storage (
    node uuid NOT NULL REFERENCES nodes (id) ON DELETE CASCADE,
    storage varchar(64) NOT NULL,
    storage_type varchar(32) NOT NULL,
    "group" varchar(64),
    PRIMARY KEY (node, storage)
);

CREATE TABLE node_backup_storage (
    node uuid NOT NULL REFERENCES nodes (id) ON DELETE CASCADE,
    storage varchar(64) NOT NULL,
    storage_type varchar(32) NOT NULL,
    "group" varchar(64),
    PRIMARY KEY (node, storage)
);

CREATE TABLE node_ports (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node uuid NOT NULL REFERENCES nodes (id) ON DELETE CASCADE,
    protocol network_protocol NOT NULL,
    start integer NOT NULL CHECK (start BETWEEN 0 AND 65535),
    "end" integer NOT NULL CHECK ("end" BETWEEN 0 AND 65535 AND "end" >= start)
);

CREATE TABLE users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(32) NOT NULL,
    auth_id varchar(255) NOT NULL UNIQUE,
    role integer NOT NULL DEFAULT 0,
    email varchar(255) NOT NULL,
    language varchar(255) NOT NULL DEFAULT 'en',
    first_name varchar(255),
    last_name varchar(255),
    daemon_password char(32)
);

CREATE TABLE projects (
    id char(6) PRIMARY KEY,
    slug varchar(64) NOT NULL UNIQUE,
    name varchar(64) NOT NULL,
    owner integer NOT NULL REFERENCES users (id)
);

CREATE INDEX projects_owner_idx ON projects (owner);

CREATE TABLE project_users (
    "user" integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    project char(6) NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    permissions bigint NOT NULL,
    PRIMARY KEY ("user", project)
);

CREATE INDEX project_users_project_user_idx ON project_users (project, "user");

CREATE TABLE servers (
    id char(6) PRIMARY KEY,
    name varchar(64) NOT NULL,
    node uuid NOT NULL REFERENCES nodes (id),
    node_server_id integer NOT NULL CHECK (node_server_id >= 0),
    project char(6) NOT NULL REFERENCES projects (id),
    cpu real,
    ram integer CHECK (ram IS NULL OR ram >= 0),
    swap integer CHECK (swap IS NULL OR swap >= 0),
    disk bigint CHECK (disk IS NULL OR disk >= 0),
    storage varchar(64) NOT NULL,
    template varchar(64) NOT NULL,
    template_extra jsonb NOT NULL,
    custom_dockerfile varchar(10000),
    suspended boolean NOT NULL DEFAULT false,
    internet_access boolean NOT NULL DEFAULT true,
    backup_limit integer CHECK (backup_limit IS NULL OR backup_limit >= 0),
    UNIQUE (node, node_server_id)
);

CREATE INDEX servers_project_idx ON servers (project);

CREATE TABLE server_ports (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server char(6) NOT NULL REFERENCES servers (id) ON DELETE CASCADE,
    name varchar(255) NOT NULL DEFAULT 'Unknown',
    host varchar(255) NOT NULL,
    internal_port integer NOT NULL CHECK (internal_port BETWEEN 0 AND 65535),
    external_ip varchar(255) NOT NULL,
    external_port int4range NOT NULL CHECK (
        NOT isempty(external_port)
        AND external_port <@ int4range(0, 65535, '[]')
    ),
    protocol network_protocol NOT NULL
);

CREATE INDEX server_ports_server_idx ON server_ports (server);

CREATE TABLE user_ssh_keys (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "user" integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name varchar(64) NOT NULL,
    public_key varchar(4096) NOT NULL,
    fingerprint_sha512 char(128) NOT NULL,
    UNIQUE ("user", fingerprint_sha512)
);

CREATE TABLE api_keys (
    key bytea PRIMARY KEY,
    name varchar(64) NOT NULL,
    permissions bigint NOT NULL
);
